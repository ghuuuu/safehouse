/**
 * The permission matrix, rendered and committed.
 *
 * Every other permission test asserts one rule. This one writes down the whole
 * answer — every account in the fixture against every document — into a file
 * that lives in the repository. The point is the diff: a change to a policy
 * arrives as "Sam gained Rose's will" in a text file rather than as a number
 * going from 137 to 136, and a reviewer who knows nothing about the SQL can
 * still see who gained what.
 *
 * It asks the plainest question there is — `select id from documents`, as each
 * user, with no joins to widen or narrow it — so the table is the policies'
 * answer rather than any one page's rendering of it. `view-as.test.ts` is what
 * proves the vault list agrees with this.
 *
 * The accounts and documents come from the fixture constants rather than from
 * the tables, so a row another test file happens to add while this one runs
 * cannot change the shape of the table.
 */

import { afterAll, beforeAll, expect, test } from "vitest";

import { DOCUMENT, USER } from "./fixture";
import {
  asUser,
  closeTestDatabase,
  owner,
  prepareTestDatabase,
} from "./test-harness";

beforeAll(async () => {
  await prepareTestDatabase();
}, 60_000);

afterAll(async () => {
  await closeTestDatabase();
});

/** Fixture declaration order, which is deliberate and stable: admin, family,
 * third party, then the awkward cases. Alphabetical would scatter them. */
const ACCOUNTS = Object.entries(USER);
const DOCUMENTS = Object.entries(DOCUMENT);

/** Pads every column to the widest cell in it, so the file stays readable. */
function columns(rows: string[][]): string {
  const widths = rows[0].map((_, i) =>
    Math.max(...rows.map((row) => row[i]?.length ?? 0)),
  );

  return rows
    .map((row) =>
      row
        .map((cell, i) => (i === row.length - 1 ? cell : cell.padEnd(widths[i])))
        .join("  ")
        .trimEnd(),
    )
    .join("\n");
}

test("the permission matrix is what the committed file says", async () => {
  const roles = new Map(
    (await owner()`select id, role from users`).map((row) => [
      row.id as string,
      row.role as string,
    ]),
  );

  const reached = new Map<string, Set<string>>();

  for (const [account, userId] of ACCOUNTS) {
    const rows = await asUser(userId, (sql) => sql`select id from documents`);
    reached.set(account, new Set(rows.map((row) => row.id as string)));
  }

  const seenBy = DOCUMENTS.map(([document, documentId]) => {
    const who = ACCOUNTS.filter(([account]) =>
      reached.get(account)!.has(documentId),
    ).map(([account]) => account);

    return [document, who.length ? who.join(", ") : "nobody"];
  });

  const totals = ACCOUNTS.map(([account, userId]) => [
    account,
    roles.get(userId) ?? "no account row",
    `${reached.get(account)!.size} of ${DOCUMENTS.length}`,
  ]);

  const rendered = [
    "The permission matrix",
    "=====================",
    "",
    "Generated by app/db/matrix.test.ts from the household in app/db/fixture.ts.",
    "Each line is the database's own answer, read as that account through the",
    "policies in drizzle/0001_permission_layer.sql and the identity boundary in",
    "0003. Not written by hand, and not to be edited by hand.",
    "",
    "Documents, and the accounts that reach them",
    "-------------------------------------------",
    "",
    columns(seenBy),
    "",
    "Accounts, and how much of the fixture they reach",
    "------------------------------------------------",
    "",
    columns(totals),
    "",
  ].join("\n");

  await expect(rendered).toMatchFileSnapshot("./matrix.txt");
});
